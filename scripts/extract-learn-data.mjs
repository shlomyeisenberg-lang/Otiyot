// One-off generator: reads the read-only reference plugins and writes the curriculum data
// (word banks, key orders, level names, lexicon) as typed TS under src/learn/data/.
// Run: node scripts/extract-learn-data.mjs && pnpm exec prettier --write src/learn/data
import fs from 'node:fs';
import vm from 'node:vm';

function load(files) {
  const ctx = vm.createContext({ console, Intl });
  const src =
    files.map((f) => fs.readFileSync(f, 'utf8')).join('\n;\n') +
    '\n;globalThis.__out = { ' +
    [
      'KEYBOARD_LAYOUT', 'ENGLISH_LAYOUT', 'WORD_BANK', 'SENTENCE_BANK', 'PARAGRAPH_BANK', 'ENGLISH_WORD_BANK', 'ENGLISH_SENTENCE_BANK',
      'ENGLISH_PARAGRAPH_BANK', 'LEVELS', 'LEVEL1_KEY_ORDER', 'ENGLISH_KEY_ORDER',
      "HEBREW_LEXICON: typeof HEBREW_LEXICON === 'undefined' ? null : HEBREW_LEXICON",
      "HEBREW_TOP_WORDS: typeof HEBREW_TOP_WORDS === 'undefined' ? null : HEBREW_TOP_WORDS",
      "HEBREW_AFFIX_CHUNKS: typeof HEBREW_AFFIX_CHUNKS === 'undefined' ? null : HEBREW_AFFIX_CHUNKS",
      "ENGLISH_LEXICON: typeof ENGLISH_LEXICON === 'undefined' ? null : ENGLISH_LEXICON",
      "ENGLISH_TOP_WORDS: typeof ENGLISH_TOP_WORDS === 'undefined' ? null : ENGLISH_TOP_WORDS",
      "ENGLISH_AFFIX_CHUNKS: typeof ENGLISH_AFFIX_CHUNKS === 'undefined' ? null : ENGLISH_AFFIX_CHUNKS",
    ].join(', ') +
    ' };';
  vm.runInContext(src, ctx);
  return JSON.parse(JSON.stringify(ctx.__out));
}

const r1 = load(['reference/plugin-3.3.0/js/constants.js']);
const r2 = load(['reference/plugin-4.2.0/js/constants.js', 'reference/plugin-4.2.0/js/lexicon.js']);

for (const k of ['KEYBOARD_LAYOUT', 'ENGLISH_LAYOUT', 'WORD_BANK', 'SENTENCE_BANK', 'PARAGRAPH_BANK', 'ENGLISH_WORD_BANK', 'ENGLISH_SENTENCE_BANK', 'ENGLISH_PARAGRAPH_BANK', 'ENGLISH_KEY_ORDER']) {
  if (JSON.stringify(r1[k]) !== JSON.stringify(r2[k])) throw new Error('banks differ between plugins: ' + k);
}

const HEADER = '// GENERATED by scripts/extract-learn-data.mjs from reference/. Do not edit by hand.\n';
const ex = (name, type, v) => `export const ${name}: ${type} = ${JSON.stringify(v)};\n`;
const bank = 'Readonly<Record<"short" | "medium" | "long" | "advanced", readonly string[]>>';

fs.writeFileSync(
  'src/learn/data/banks.ts',
  HEADER +
    ex('HE_WORD_BANK', bank, r2.WORD_BANK) +
    ex('HE_SENTENCES', 'readonly string[]', r2.SENTENCE_BANK) +
    ex('HE_PARAGRAPHS', 'readonly string[]', r2.PARAGRAPH_BANK) +
    ex('EN_WORD_BANK', bank, r2.ENGLISH_WORD_BANK) +
    ex('EN_SENTENCES', 'readonly string[]', r2.ENGLISH_SENTENCE_BANK) +
    ex('EN_PARAGRAPHS', 'readonly string[]', r2.ENGLISH_PARAGRAPH_BANK),
);

const levelType = 'readonly { id: number; he: string; heDesc: string; en: string; enDesc: string }[]';
const lv = (L) => L.map((l) => ({ id: l.id, he: l.name, heDesc: l.desc, en: l.en, enDesc: l.enDesc }));
const codeToKey = (c) => c;
const letters = (L, re) => Object.values(L).filter((c) => re.test(c));
fs.writeFileSync(
  'src/learn/data/curriculum.ts',
  HEADER +
    ex('HE_LEVELS_TRACK1', levelType, lv(r1.LEVELS)) +
    ex('HE_LEVELS_TRACK2', levelType, lv(r2.LEVELS)) +
    ex('HE_KEY_ORDER_TRACK1', 'readonly string[]', r1.LEVEL1_KEY_ORDER.map(codeToKey)) +
    ex('HE_KEY_ORDER_TRACK2', 'readonly string[]', r2.LEVEL1_KEY_ORDER.map(codeToKey)) +
    ex('EN_KEY_ORDER', 'readonly string[]', r2.ENGLISH_KEY_ORDER) +
    '// Letters in the original layout order (decides the order random picks are drawn in).\n' +
    ex('HE_LETTERS', 'readonly string[]', letters(r2.KEYBOARD_LAYOUT, /^[\u05D0-\u05EA]$/)) +
    ex('EN_LETTERS', 'readonly string[]', letters(r2.ENGLISH_LAYOUT, /^[a-zA-Z]$/)),
);

const aff = 'Readonly<{ prefixes: readonly (readonly [string, readonly string[]])[]; suffixes: readonly (readonly [string, readonly string[]])[]; clusters: readonly string[] }>';
fs.writeFileSync(
  'src/learn/data/lexicon.ts',
  HEADER +
    ex('HE_LEXICON', 'readonly string[]', r2.HEBREW_LEXICON) +
    ex('HE_TOP_WORDS', 'readonly string[]', r2.HEBREW_TOP_WORDS) +
    ex('HE_AFFIX_CHUNKS', aff, r2.HEBREW_AFFIX_CHUNKS) +
    ex('EN_LEXICON', 'readonly string[]', r2.ENGLISH_LEXICON) +
    ex('EN_TOP_WORDS', 'readonly string[]', r2.ENGLISH_TOP_WORDS) +
    ex('EN_AFFIX_CHUNKS', aff, r2.ENGLISH_AFFIX_CHUNKS),
);
console.log('ok', Array.isArray(r2.HEBREW_LEXICON), r2.HEBREW_LEXICON?.length, r2.ENGLISH_LEXICON?.length);
